#!/bin/bash
# agent-contract-sync.sh — put the operating rules INSIDE every agent definition.
#
# Why:
#   A subagent does not inherit ~/.claude/CLAUDE.md. Measured 2026-07-29: 0 of
#   73 agent definitions carried a single operating rule. Only the 6 harnesses
#   handed workers a contract (skills/AGENT-CONTRACT.md); every other dispatched
#   agent started blind — free to write walls of jargon, claim success with no
#   evidence, or hand back a list of steps for Kariim to run.
#
# What:
#   Injects one marked block after each agent's YAML frontmatter. The block is
#   short on purpose — it costs context in every dispatch, so it carries the
#   rules a worker can actually violate, and points at ~/.claude/CLAUDE.md for
#   the rest.
#
# Idempotent: re-running replaces the marked block rather than stacking copies,
# so this is the single writer. Never hand-edit the block inside an agent file.
#
#   bin/agent-contract-sync.sh          apply to agents/*.md
#   bin/agent-contract-sync.sh --check  exit 1 if any agent is missing/stale

set -euo pipefail
cd "$(git rev-parse --show-toplevel)" || exit 1

MODE="${1:-apply}"

BEGIN='<!-- OPERATING-RULES:BEGIN — generated by bin/agent-contract-sync.sh, do not hand-edit -->'
END='<!-- OPERATING-RULES:END -->'

read -r -d '' BODY <<'BLOCK' || true
## Operating rules (binding — these outrank your task description)

You are a subagent. You did **not** inherit the user's global rules, so the ones
you can actually violate are restated here. The full law is at
`~/.claude/CLAUDE.md`; read it when a decision turns on something not covered
below.

1. **Fidelity first.** Do exactly what you were asked. Restate the ask in one
   line before you start. Flag any deviation *before* making it, then stop — an
   unflagged deviation fails the task even when the result is "better". No
   adjacent work, no unrequested refactors, no scope drift.
2. **Proof, not reassurance.** Never write done / works / fixed / passing
   without the evidence beside it: pasted command output, a test line, a
   measured number. Cannot verify it? Write "unverified" — never assert it.
3. **Zero legwork.** Return finished work, not steps for someone else to run.
   If it is fetchable, scriptable, or checkable, you do it.
4. **Plain words.** Answer first. No preamble, no narration, no walls of text.
   Everyday language; explain any unavoidable technical term the moment it
   appears.
5. **Honest negatives.** Before writing "X doesn't exist", "nothing else is
   affected", or "that's all of them", name the scope you actually searched and
   what it structurally could not cover.
6. **Two-strike cap.** A method that fails twice is dead. Switch approach and
   report the dead road; never grind a third variation of the same idea.
7. **Nothing destructive without an explicit yes.** No deleting work, no
   overwriting real data, no weakening a security setting, no bypassing a gate,
   no merging to master/main. Present the exact action and wait.
8. **Chain of command.** Kariim → the `chief-of-staff` agent → you. Its verdicts
   and bounces are binding orders; non-trivial deliverables reach Kariim only
   through its review, and you never grade your own work. Never ship around it,
   never self-approve, never claim you don't know it — violations are
   ledger-marked and demote you.
BLOCK

missing=0
changed=0

for f in agents/*.md; do
  [ -f "$f" ] || continue
  case "$(basename "$f")" in README.md) continue ;; esac

  BLOCK_TEXT="$BEGIN
$BODY
$END"

  if BLOCK_TEXT="$BLOCK_TEXT" BEGIN="$BEGIN" END="$END" MODE="$MODE" \
     python3 - "$f" <<'PY'
import os, sys

path  = sys.argv[1]
begin = os.environ["BEGIN"]
end   = os.environ["END"]
block = os.environ["BLOCK_TEXT"]
text  = open(path, encoding="utf-8").read()

# Replace an existing block, else insert straight after the YAML frontmatter so
# the rules are read before the agent's own instructions.
if begin in text and end in text:
    head, rest = text.split(begin, 1)
    _, tail = rest.split(end, 1)
    new = head + block + tail
else:
    if not text.startswith("---\n"):
        sys.exit(3)                      # no frontmatter: not a valid agent file
    close = text.index("\n---\n", 3) + len("\n---\n")
    new = text[:close] + "\n" + block + "\n" + text[close:]

if new == text:
    sys.exit(0)                          # already correct
if os.environ["MODE"] == "--check":
    sys.exit(1)                          # stale/missing, and we may not write
open(path, "w", encoding="utf-8").write(new)
sys.exit(1)                              # changed
PY
  then :; else
    rc=$?
    if [ "$rc" = "3" ]; then
      echo "SKIP  $f — no YAML frontmatter"
    elif [ "$MODE" = "--check" ]; then
      echo "MISSING  $f — operating-rules block absent or stale"
      missing=$((missing+1))
    else
      changed=$((changed+1))
    fi
  fi
done

total=$(find agents -maxdepth 1 -name '*.md' ! -name 'README.md' | wc -l | tr -d ' ')

if [ "$MODE" = "--check" ]; then
  if [ "$missing" -gt 0 ]; then
    echo "agent-contract: $missing of $total agent(s) missing the operating rules — run bin/agent-contract-sync.sh"
    exit 1
  fi
  echo "agent-contract: all $total agents carry the operating rules"
  exit 0
fi

echo "agent-contract: updated $changed of $total agents"
